'use strict';
// Типы связей фактов. Разные слова для одной связи («живёт в», «переехала в», «проживает в»)
// сводятся к одному типу, чтобы противоречия и дубли находились, как бы факт ни был сказан.
// single — у субъекта одно значение (живёт в одном городе): другое значение = противоречие.
// multi — значений может быть много (любит чай и кофе): это не противоречие.
// polarity -1 — отрицание («не любит»): «любит X» и «не любит X» спорят между собой.
const TYPES=[
 {relation:'живёт в',single:true,re:/^(живет|проживает|обитает|поселил\S*|переехал\S*|перебрал\S*)(\s+(в|во|на))?$/},
 {relation:'работает в',single:true,re:/^(работает|трудится|устроил\S*|служит)\s+(в|во|на)$/},
 {relation:'учится в',single:true,re:/^(учится|обучается|поступил\S*)\s+(в|во|на)$/},
 {relation:'зовут',single:true,re:/^(зовут|имя|по имени|называют)$/},
 {relation:'день рождения',single:true,re:/^(день рождения|дата рождения|родил(ся|ась)|д\.?\s?р\.?)$/},
 {relation:'возраст',single:true,re:/^(возраст|лет|исполнилось)$/},
 {relation:'женат на',single:true,re:/^(женат на|замужем за|муж|жена|супруг|супруга)$/},
 {relation:'любит',polarity:-1,re:/^(не любит|ненавидит|не переносит|терпеть не может|не нравится|не выносит)$/},
 {relation:'любит',re:/^(любит|обожает|нравится|предпочитает|в восторге от)$/},
 {relation:'умеет',re:/^(умеет|может|владеет|способен|способна)$/},
 {relation:'умеет',polarity:-1,re:/^(не умеет|не может|не владеет)$/},
 {relation:'знает',re:/^(знает|знаком с|знакома с)$/},
 {relation:'дружит с',re:/^(дружит с|друг|подруга|друзья с)$/},
];
// Связи без своего типа: эти по смыслу допускают много значений, остальные считаются единственными (как раньше).
const MULTI=/любит|обожает|нрав|умеет|говорит на|увлекается|играет|занимается|пьет|ест|знает|дружит|читает|смотрит|слушает|коллекционирует|^это$|^есть$|^имеет$|^у него$|^у нее$/;
const clean=s=>String(s||'').toLocaleLowerCase().replace(/ё/g,'е').replace(/[«»"'.,;:!?()]/g,' ').replace(/\s+/g,' ').trim();
function classify(predicate){
 const p=clean(predicate);
 for(const t of TYPES)if(t.re.test(p))return {relation:t.relation,polarity:t.polarity||1,single:!!t.single};
 const neg=/^не\s+/.test(p),base=neg?p.slice(3):p;
 return {relation:base||p,polarity:neg?-1:1,single:!MULTI.test(base)};
}
// Сущность для сравнения: регистр, «ё», кавычки и «г.»/«город» не важны.
function entityKey(s){return clean(s).replace(/^(г|город|гор|пос|с|д)\s+/,'').trim()}
module.exports={classify,entityKey,clean};
